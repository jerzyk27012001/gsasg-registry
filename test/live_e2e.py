import asyncio, json
from playwright.async_api import async_playwright
import os
URL="file://"+os.path.abspath(os.path.join(os.path.dirname(__file__),"..","dist-mock","index.html"))
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); ctx=await b.new_context(viewport={"width":1366,"height":900})
        pg=await ctx.new_page()
        errs=[]; pg.on("pageerror", lambda e: errs.append(str(e)))
        await pg.goto(URL); await pg.evaluate("localStorage.clear()"); await pg.goto(URL); await pg.wait_for_timeout(500)
        say=lambda *a: print(" ", *a)
        async def db(expr): return await pg.evaluate(f"(()=>{{const DB=window.__mockDB; return {expr};}})()")

        print("1. landing → Enter the registry → sign-in")
        await pg.click("text=Enter the registry"); await pg.wait_for_timeout(300)
        say("auth screen:", await pg.is_visible(".authcard"), "| nav hidden:", not await pg.is_visible(".nav"))

        print("2. George creates the first account → INI admin, empty registry")
        await pg.click(".authcard >> text=Create account")
        await pg.fill(".authcard input[autocomplete=name]","George Gregorczyk")
        await pg.fill(".authcard input[type=email]","george@example.com")
        await pg.fill(".authcard input[type=password]","correct-horse-1")
        await pg.click(".authcard button[type=submit]"); await pg.wait_for_timeout(500)
        say("title:", await pg.inner_text("#scTitle"), "| who:", (await pg.inner_text("#whoBox")).replace("\n"," / "), "| cases:", await pg.evaluate("CASES.length"))

        print("3. Load demo patients from Users & access")
        await pg.evaluate("go('users')"); await pg.wait_for_timeout(300)
        await pg.click("text=Load 112 demo patients"); await pg.wait_for_timeout(1200)
        say("cases in app:", await pg.evaluate("CASES.length"), "| in database:", await db("DB.cases.length"), "| first id:", await db("DB.cases[0].id"))

        print("4. Invite a Lakeshore site user")
        await pg.fill(".userrow input[type=email]","lake@example.com")
        await pg.fill(".userrow input[placeholder='Full name']","Dr. R. Halvorsen")
        sels = await pg.query_selector_all(".mt .userrow select")
        await sels[-2].select_option("site_user"); await sels[-1].select_option("Lakeshore Spine Center — Chicago")
        await pg.click("button:text('Invite')"); await pg.wait_for_timeout(400)
        say("invites:", await db("JSON.stringify(DB.invites.map(i=>[i.email,i.role,i.site]))"))

        print("5. Enroll a real-looking case; it gets a server case number and survives a reload")
        await pg.evaluate("draft=null; go('new')"); await pg.wait_for_timeout(400)
        await pg.fill("#fld_name","Test Patient"); await pg.select_option("#fld_race", index=2); await pg.fill("#fld_symptomMonths","12")
        await pg.click("text=Save operative record"); await pg.wait_for_timeout(900)
        newid = await pg.evaluate("openCaseId")
        say("new case:", newid, "| saved in database:", await db(f"!!DB.cases.find(c=>c.id==='{newid}')"), "| save chip:", await pg.inner_text("#saveChip"))
        await pg.goto(URL); await pg.wait_for_timeout(900)
        say("after reload — signed in:", await pg.inner_text("#whoBox") if await pg.is_visible("#whoBox") else None,
            "| cases:", await pg.evaluate("CASES.length"), "| still has", newid, ":", await pg.evaluate(f"!!CASES.find(c=>c.id==='{newid}')"))
        dobtype = await pg.evaluate("Object.prototype.toString.call(CASES.find(c=>c.id.startsWith('DEMO')).date)")
        say("dates revived as:", dobtype)

        print("6. Add an adverse event → saved to the database")
        cid = await pg.evaluate("CASES.find(c=>c.site.startsWith('Lakeshore')).id")
        await pg.evaluate(f"openCase('{cid}')"); await pg.wait_for_timeout(400)
        before = await db(f"(DB.cases.find(c=>c.id==='{cid}').data.aes||[]).length")
        await pg.evaluate(f"""(()=>{{const c=CASES.find(x=>x.id==='{cid}'); c.aes.push({{type:'Dysphagia',onset:'2026-11-20',severity:'Grade 1 — mild',serious:'No'}}); logAudit(c,'Adverse event reported','Dysphagia','—','Grade 1');}})()""")
        await pg.wait_for_timeout(900)
        say("AEs in database:", before, "→", await db(f"DB.cases.find(c=>c.id==='{cid}').data.aes.length"), "| chip:", await pg.inner_text("#saveChip"))

        print("6b. New screens as INI; publish benchmarks; demo backfill")
        await pg.evaluate("go('access')"); await pg.wait_for_timeout(400)
        say("access screen:", await pg.is_visible("text=Outcomes by indication"), "| denied rows:", await pg.evaluate("CASES.filter(c=>c.access&&c.access.priorAuth==='Denied').length"))
        await pg.evaluate("go('bench')"); await pg.wait_for_timeout(400)
        await pg.click("text=Publish benchmarks to sites"); await pg.wait_for_timeout(600)
        say("benchmarks in database:", await db("DB.benchmarks.length===1 && DB.benchmarks[0].data.cases"))
        did = await db("DB.cases.find(c=>c.id.startsWith('DEMO')).id")
        await db(f"(()=>{{const r=DB.cases.find(c=>c.id==='{did}'); delete r.data.access; delete r.data.periop; delete r.data.outsideCare; localStorage.setItem('mock_db',JSON.stringify(DB)); return 1;}})()")
        await pg.goto(URL); await pg.wait_for_timeout(1500)
        say("old demo record backfilled in app:", await pg.evaluate(f"!!CASES.find(c=>c.id==='{did}').access.payer"),
            "| and saved back:", await db(f"!!DB.cases.find(c=>c.id==='{did}').data.access"))
        await pg.evaluate(f"openCase('{did}')"); await pg.wait_for_timeout(300)
        say("case page shows coverage card:", await pg.is_visible("text=Coverage & access"))

        print("7. Sign out; Lakeshore user signs up from the invite → sees only Lakeshore")
        await pg.click("#switchBtn"); await pg.wait_for_timeout(400)
        await pg.click(".authcard >> text=Create account")
        await pg.fill(".authcard input[type=email]","lake@example.com"); await pg.fill(".authcard input[type=password]","another-pass-2")
        await pg.click(".authcard button[type=submit]"); await pg.wait_for_timeout(600)
        sites = await pg.evaluate("[...new Set(CASES.map(c=>c.site))]")
        say("who:", (await pg.inner_text("#whoBox")).replace("\n"," / "), "| cases:", await pg.evaluate("CASES.length"), "| sites:", sites)
        say("Users & access in nav:", await pg.evaluate("[...document.querySelectorAll('.navitem')].some(n=>n.textContent.includes('Users'))"))
        await pg.evaluate("go('users')"); await pg.wait_for_timeout(200); say("go('users') lands on:", await pg.inner_text("#scTitle"))
        r = await pg.evaluate("""(async()=>{ const {error}=await sb.from('cases').upsert({id:'HACK-1',site:'Neurosurgery & Spine Group — Santa Monica',data:{}}); return error&&error.message; })()""")
        say("writing to another site is refused:", r)

        await pg.evaluate("go('bench')"); await pg.wait_for_timeout(900)
        btxt = await pg.inner_text("#content")
        say("site user benchmarks: registry median shown:", "registry median" in btxt, "| other sites' surgeons named:",
            any(n in btxt for n in await pg.evaluate("SURGEONS.filter(s=>!scopedSurgeons().includes(s))")))
        say("site user access screen sees only own site:", await pg.evaluate("go('access'), CASES.every(c=>c.site.startsWith('Lakeshore'))"))

        print("8. A stranger signs up → waiting for approval → INI approves → access")
        await pg.click("#switchBtn"); await pg.wait_for_timeout(300)
        await pg.click(".authcard >> text=Create account")
        await pg.fill(".authcard input[type=email]","new.doc@example.com"); await pg.fill(".authcard input[type=password]","pending-pass-3")
        await pg.click(".authcard button[type=submit]"); await pg.wait_for_timeout(500)
        say("pending screen:", await pg.is_visible("text=Waiting for approval"), "| cases loaded:", await pg.evaluate("CASES.length"))
        await pg.screenshot(path="/home/claude/shots/live_pending.png")
        await pg.click(".authcard >> text=Sign out"); await pg.wait_for_timeout(300)
        await pg.fill(".authcard input[type=email]","george@example.com"); await pg.fill(".authcard input[type=password]","correct-horse-1")
        await pg.click(".authcard button[type=submit]"); await pg.wait_for_timeout(600)
        await pg.evaluate("go('users')"); await pg.wait_for_timeout(400)
        await pg.screenshot(path="/home/claude/shots/live_users.png", full_page=True)
        rows = await pg.query_selector_all(".userrow")
        pend = rows[0]; ss = await pend.query_selector_all("select")
        await ss[0].select_option("site_user"); await ss[1].select_option("Riverbend Neurosurgery — Austin")
        await (await pend.query_selector("button")).click(); await pg.wait_for_timeout(400)
        say("profile now:", await db("JSON.stringify(DB.profiles.find(p=>p.email==='new.doc@example.com'))"))

        print("9. Wrong password message; remove demo patients")
        await pg.click("#switchBtn"); await pg.wait_for_timeout(300)
        await pg.fill(".authcard input[type=email]","george@example.com"); await pg.fill(".authcard input[type=password]","wrong-password")
        await pg.click(".authcard button[type=submit]"); await pg.wait_for_timeout(300)
        say("error shown:", await pg.inner_text(".authcard .banner"))
        await pg.fill(".authcard input[type=email]","george@example.com"); await pg.fill(".authcard input[type=password]","correct-horse-1")
        await pg.click(".authcard button[type=submit]"); await pg.wait_for_timeout(600)
        await pg.evaluate("go('users')"); await pg.wait_for_timeout(400)
        await pg.click("text=Remove demo patients"); await pg.wait_for_timeout(300)
        await pg.click("text=Tap again to remove them all"); await pg.wait_for_timeout(600)
        say("cases left:", await db("DB.cases.map(c=>c.id).join(',')"))
        print("\npage errors:", errs or "none")
        await b.close()
asyncio.run(main())
